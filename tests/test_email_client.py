class TestGetEmailClient(unittest.TestCase):
    def _clear_env(self, monkeypatch_dict):
        """Remove email env vars from os.environ for the duration of a test."""
        for key in ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD"):
            monkeypatch_dict.pop(key, None)

    def test_returns_none_when_no_env_vars(self):
        from email_client import get_email_client

        env_backup = {k: os.environ.pop(k, None) for k in
                      ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD")}
        try:
            result = get_email_client()
            self.assertIsNone(result)
        finally:
            for k, v in env_backup.items():
                if v is not None:
                    os.environ[k] = v

    def test_returns_none_when_only_sender_set(self):
        from email_client import get_email_client

        env_backup = {k: os.environ.pop(k, None) for k in
                      ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD")}
        try:
            os.environ["EMAIL_SENDER"] = "me@gmail.com"
            result = get_email_client()
            self.assertIsNone(result)
        finally:
            for k, v in env_backup.items():
                if v is not None:
                    os.environ[k] = v
            os.environ.pop("EMAIL_SENDER", None)

    def test_returns_none_when_sender_empty_string(self):
        from email_client import get_email_client

        env_backup = {k: os.environ.pop(k, None) for k in
                      ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD")}
        try:
            os.environ["EMAIL_SENDER"] = ""
            os.environ["EMAIL_RECIPIENT"] = "them@gmail.com"
            os.environ["GMAIL_APP_PASSWORD"] = "pw"
            result = get_email_client()
            self.assertIsNone(result)
        finally:
            for k, v in env_backup.items():
                if v is not None:
                    os.environ[k] = v
            for k in ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD"):
                os.environ.pop(k, None)

    def test_returns_email_client_when_all_vars_set(self):
        from email_client import EmailClient, get_email_client

        env_backup = {k: os.environ.pop(k, None) for k in
                      ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD")}
        try:
            os.environ["EMAIL_SENDER"] = "me@gmail.com"
            os.environ["EMAIL_RECIPIENT"] = "them@gmail.com"
            os.environ["GMAIL_APP_PASSWORD"] = "abcd-efgh-ijkl-mnop"
            result = get_email_client()
            self.assertIsNotNone(result)
            self.assertIsInstance(result, EmailClient)
        finally:
            for k, v in env_backup.items():
                if v is not None:
                    os.environ[k] = v
            for k in ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD"):
                os.environ.pop(k, None)

    def test_returns_none_when_password_missing(self):
        from email_client import get_email_client

        env_backup = {k: os.environ.pop(k, None) for k in
                      ("EMAIL_SENDER", "EMAIL_RECIPIENT", "GMAIL_APP_PASSWORD")}
        try:
            os.environ["EMAIL_SENDER"] = "me@gmail.com"
            os.environ["EMAIL_RECIPIENT"] = "them@gmail.com"
            # GMAIL_APP_PASSWORD intentionally not set
            result = get_email_client()
            self.assertIsNone(result)
        finally:
            for k, v in env_backup.items():
                if v is not None:
                    os.environ[k] = v
            for k in ("EMAIL_SENDER", "EMAIL_RECIPIENT"):
                os.environ.pop(k, None)


