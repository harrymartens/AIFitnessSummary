class TestSendReport(unittest.TestCase):
    def _smtp_ctx(self):
        """Return a context-manager mock that mimics SMTP_SSL usage."""
        mock_server = MagicMock()
        mock_cm = MagicMock()
        mock_cm.__enter__ = MagicMock(return_value=mock_server)
        mock_cm.__exit__ = MagicMock(return_value=False)
        return mock_cm, mock_server

    @patch("email_client.smtplib.SMTP_SSL")
    def test_smtp_ssl_called_with_correct_host_port(self, mock_smtp_ssl):
        mock_cm, mock_server = self._smtp_ctx()
        mock_smtp_ssl.return_value = mock_cm

        client = _make_client()
        client.send_report("weekly", "2026-03-05", "# Report")

        mock_smtp_ssl.assert_called_once()
        call_args = mock_smtp_ssl.call_args
        # First two positional-or-keyword args: host, port
        args, kwargs = call_args
        host = args[0] if args else kwargs.get("host")
        port = args[1] if len(args) > 1 else kwargs.get("port")
        self.assertEqual(host, "smtp.gmail.com")
        self.assertEqual(port, 465)

    @patch("email_client.smtplib.SMTP_SSL")
    def test_login_called_with_credentials(self, mock_smtp_ssl):
        mock_cm, mock_server = self._smtp_ctx()
        mock_smtp_ssl.return_value = mock_cm

        client = _make_client(sender="me@gmail.com", pw="secret-pw")
        client.send_report("weekly", "2026-03-05", "# Report")

        mock_server.login.assert_called_once_with("me@gmail.com", "secret-pw")

    @patch("email_client.smtplib.SMTP_SSL")
    def test_sendmail_called(self, mock_smtp_ssl):
        mock_cm, mock_server = self._smtp_ctx()
        mock_smtp_ssl.return_value = mock_cm

        client = _make_client(sender="me@gmail.com", recipient="them@gmail.com")
        result = client.send_report("weekly", "2026-03-05", "# Report")

        mock_server.sendmail.assert_called_once()
        self.assertTrue(result)

    @patch("email_client.smtplib.SMTP_SSL")
    def test_send_report_returns_false_on_smtp_error(self, mock_smtp_ssl):
        mock_smtp_ssl.side_effect = smtplib.SMTPException("connection refused")

        client = _make_client()
        result = client.send_report("weekly", "2026-03-05", "# Report")

        self.assertFalse(result)

    @patch("email_client.smtplib.SMTP_SSL")
    def test_email_contains_both_plain_and_html_parts(self, mock_smtp_ssl):
        """The message sent should be multipart/alternative with plain + HTML."""
        captured = {}

        def fake_sendmail(frm, to, msg_str):
            captured["msg"] = msg_str

        mock_cm, mock_server = self._smtp_ctx()
        mock_server.sendmail.side_effect = fake_sendmail
        mock_smtp_ssl.return_value = mock_cm

        client = _make_client()
        client.send_report("monthly", "2026-03-31", "# Hello\n\nWorld")

        self.assertIn("msg", captured)
        msg_str = captured["msg"]
        self.assertIn("text/plain", msg_str)
        self.assertIn("text/html", msg_str)

    @patch("email_client.smtplib.SMTP_SSL")
    def test_subject_in_sent_message(self, mock_smtp_ssl):
        """Subject header should reference 'Weekly Fitness Review'.

        The MIME encoder may apply RFC-2047 quoted-printable encoding to the
        Subject header when it contains non-ASCII characters (e.g. em dash),
        so we parse the message back out with email.parser to read the
        decoded header value.
        """
        import email as email_module

        captured = {}

        def fake_sendmail(frm, to, msg_str):
            captured["msg"] = msg_str

        mock_cm, mock_server = self._smtp_ctx()
        mock_server.sendmail.side_effect = fake_sendmail
        mock_smtp_ssl.return_value = mock_cm

        client = _make_client()
        client.send_report("weekly", "2026-03-05", "# Hello")

        raw = captured["msg"]
        parsed = email_module.message_from_string(raw)
        # Decode RFC-2047-encoded header words
        from email.header import decode_header, make_header
        subject = str(make_header(decode_header(parsed["Subject"])))
        self.assertIn("Weekly Fitness Digest", subject)


